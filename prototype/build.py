"""Bundle the prototype into one self-contained index.html.
Edit dev.html, styles.css and js/*.js, then run: python3 prototype/build.py"""
import base64, pathlib, re
here = pathlib.Path(__file__).parent
html = (here / "dev.html").read_text()

def data_uri(rel, mime):
    return f"data:{mime};base64," + base64.b64encode((here / rel).read_bytes()).decode()

html = html.replace('href="icons/favicon.svg"', 'href="' + data_uri("icons/favicon.svg", "image/svg+xml") + '"')
html = html.replace('href="icons/favicon-32.png"', 'href="' + data_uri("icons/favicon-32.png", "image/png") + '"')
html = html.replace('href="icons/apple-touch-icon.png"', 'href="' + data_uri("icons/apple-touch-icon.png", "image/png") + '"')
css = (here / "styles.css").read_text()
html = html.replace('<link rel="stylesheet" href="styles.css">', "<style>\n" + css + "\n</style>")

def inline(m):
    code = (here / m.group(1)).read_text().replace("</script", "<\\/script")
    return "<script>\n" + code + "\n</script>"
html = re.sub(r'<script src="(js/[^"]+)"></script>', inline, html)
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build.py from dev.html. Edit the source files, not this one. -->", 1)
(here / "index.html").write_text(html)
print("wrote index.html", len(html) // 1024, "KB")
